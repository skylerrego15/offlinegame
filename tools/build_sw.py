# Regenerates sw.js with the full offline file list and a content hash version.
import os, hashlib, json
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files, h = [], hashlib.sha1()
for d in ['', 'css', 'js', 'assets/creatures', 'assets/eggs', 'assets/icons']:
    p = os.path.join(root, d)
    for f in sorted(os.listdir(p)):
        fp = os.path.join(p, f)
        if os.path.isfile(fp) and not f.startswith('.') and f not in ('sw.js', 'README.md', 'DrownedClutch.html') and not f.endswith('.py'):
            rel = (d + '/' + f) if d else f
            files.append(rel)
            h.update(rel.encode()); h.update(open(fp, 'rb').read())
ver = h.hexdigest()[:10]
sw = f"""// generated by tools/build_sw.py — offline cache for Drowned Clutch
const CACHE = 'dc-{ver}';
const FILES = {json.dumps(['./'] + files, indent=1)};
self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', (e) => {{
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('fetch', (e) => {{
  if (e.request.method !== 'GET') return;
  e.respondWith(
    caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => hit || fetch(e.request).then((res) => {{
      if (res.ok && new URL(e.request.url).origin === location.origin) {{
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(e.request, copy));
      }}
      return res;
    }}).catch(() => caches.match('./')))
  );
}});
"""
open(os.path.join(root, 'sw.js'), 'w').write(sw)
print(ver, len(files), 'files')
