# Regenerates sw.js (offline cache) and js/version.js with a content-hash version.
import os, hashlib, json
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP = ('sw.js', 'README.md', 'DrownedClutch.html', 'version.js')
files, h = [], hashlib.sha1()
for d in ['', 'css', 'js', 'assets/creatures', 'assets/eggs', 'assets/icons']:
    p = os.path.join(root, d)
    for f in sorted(os.listdir(p)):
        fp = os.path.join(p, f)
        if os.path.isfile(fp) and not f.startswith('.') and not f.endswith('.py') and f not in SKIP:
            rel = (d + '/' + f) if d else f
            files.append(rel)
            h.update(rel.encode()); h.update(open(fp, 'rb').read())
files.append('js/version.js')
ver = h.hexdigest()[:10]
open(os.path.join(root, 'js', 'version.js'), 'w').write(f"export const VERSION = '{ver}';\n")
sw = f"""// generated by tools/build_sw.py — offline support for Drowned Clutch
// Code is network-first (always newest when online, cached copy when offline).
// Art is cache-first. Every update installs itself and the page reloads into it.
const CACHE = 'dc-{ver}';
const FILES = {json.dumps(['./'] + files, indent=1)};
self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => Promise.all(FILES.map((f) => c.add(new Request(f, {{ cache: 'reload' }})).catch(() => {{}})))).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', (e) => {{
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
}});
function fromNet(req) {{
  return fetch(req, {{ cache: 'no-store' }}).then((res) => {{
    if (res.ok) {{ const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }}
    return res;
  }});
}}
self.addEventListener('fetch', (e) => {{
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;
  const isArt = /\\.(webp|png|jpg)$/.test(url.pathname);
  if (isArt) {{
    e.respondWith(caches.match(req, {{ ignoreSearch: true }}).then((hit) => hit || fromNet(req)));
    return;
  }}
  e.respondWith(
    Promise.race([
      fromNet(req),
      new Promise((_, rej) => setTimeout(() => rej(new Error('slow')), 4000)),
    ]).catch(() => caches.match(req, {{ ignoreSearch: true }}).then((hit) => hit || caches.match('./')))
  );
}});
"""
open(os.path.join(root, 'sw.js'), 'w').write(sw)
print(ver, len(files), 'files')
